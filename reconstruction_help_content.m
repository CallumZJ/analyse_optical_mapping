function catalog = reconstruction_help_content()
%% Reconstruction help content
% Collin Snitchler
% 14.09.2026
% Help text for the Reconstruction/Reprojection tab, shown by the Guide
% button and File > Reconstruction Help.
% Inputs: none.
% Outputs: catalog.version (1) and catalog.topics(k) with fields
