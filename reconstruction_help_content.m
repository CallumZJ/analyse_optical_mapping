% -------------------------------------------------------------------------
function t = topic(id, title, body, citation_keys, journeys, state_terms)
% One topic struct. The text is written in ASCII here; the user reads the
% symbols: >= and <= as the signs, "18 deg" as 18 followed by the degree
% sign
body = strrep(strrep(body, '>=', char(8805)), '<=', char(8804));
body = regexprep(body, '(\d) deg\>', ['$1' char(176)]);
% "3x3" with the multiplication sign
body = regexprep(body, '\<(\d)x(\d)\>', ['$1' char(215) '$2']);
% Paths in the app's one display style, backslashes
body = rabbit_reconstruction_tab.display_paths_in(body);
t = struct( ...
    'id',            id, ...
    'title',         title, ...
    'body',          {body}, ...
    'citation_keys', {citation_keys}, ...
    'journeys',      {journeys}, ...
    'state_terms',   {state_terms});
end
