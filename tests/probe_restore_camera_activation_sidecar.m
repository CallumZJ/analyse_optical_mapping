function probe_restore_camera_activation_sidecar
%% Camera bounds, activation status format and sidecar recovery
% Collin Snitchler
% 13.09.2026
% Checks the camera view angle bounds, the persisted activation status
% format, projected zero and NaN values and the public recover_sidecar method.
repo_dir = fileparts(fileparts(mfilename('fullpath')));
addpath(repo_dir);
tab = rabbit_reconstruction_tab();
pass = 0;
fail = 0;

fprintf('E1C1: documented CameraViewAngle lower endpoint +0 is accepted\n');
cam = camera_record(0);
[ok0, err0, ~] = tab.validate_camera_state(cam);
record('E1C1', ok0 && isempty(err0), err0);

fprintf('E1C2: next representable value below 180 is accepted; 180 is rejected\n');
upper = java.lang.Math.nextDown(180.0);
[ok_upper, err_upper, wire_upper] = tab.validate_camera_state(camera_record(upper)); %#ok<ASGLU>
[ok_180, err_180, ~] = tab.validate_camera_state(camera_record(180));
record('E1C2', ok_upper && ~ok_180 && ~isempty(err_180), ...
    sprintf('upper=%s reject180=%s', err_upper, err_180));

fprintf('E2C1: activation status wire is the closed persisted schema\n');
prov = struct('map_kind', 'activation_time', 'units', 'ms', ...
    'method', struct('name', 'activation_time_pipeline', 'version', 'method-v1', ...
    'parameters_json', method_parameters_json(tab), 'parameters_sha256', repmat('0', 1, 64)), ...
    'time_reference', struct('kind', 'relative_to_first_frame', ...
    'anchor_frame', '1', 'applied_offset_ms', '0000000000000000', 'parent', []), ...
    'recording_identity', struct('source_type', 'file'), ...
    'geometry', struct('contract_version', 'geometry-v1'), ...
    'geometry_digest', repmat('0', 1, 64), ...
    'projection_contract', struct('contract_version', 'projection-v1'), ...
    'projection_contract_digest', repmat('0', 1, 64), ...
    'target_mesh_digest', repmat('1', 1, 64));
prov.method.parameters_sha256 = tab.restore_domain_digest( ...
    'OM-ACTIVATION-METHOD', 'method-v1', jsondecode(prov.method.parameters_json));
[map_ok, map_err, activation] = tab.validate_activation_state(single([0 NaN; 1 2]), prov);
closed_fields = map_ok && isequal(sort(fieldnames(activation)), sort({ ...
    'schema', 'status', 'map_kind', 'units', 'method', 'time_reference', ...
    'recording_identity', 'geometry', 'projection_contract', 'map_summary', ...
    'map_digest', 'geometry_digest', 'projection_contract_digest', ...
    'projected_output', 'provenance_digest'}'));
record('E2C1', closed_fields, map_err);

activation_extra = activation;
activation_extra.extra = 'reject';
[extra_ok, extra_err, ~] = tab.validate_activation_compatibility( ...
    activation_extra, activation);
record('E2C2', ~extra_ok && contains(extra_err, 'extra or missing'), extra_err);

method_bad = activation;
method_bad.method.parameters_json = '[]';
[method_ok, method_err, ~] = tab.validate_activation_compatibility( ...
    method_bad, activation);
record('E2C3', ~method_ok && contains(method_err, 'method'), method_err);

fprintf('E2C4: spatial_filter method parameters are semantically closed\n');
spatial_payload = struct('schema', 'method-parameters-v1', ...
    'operation', 'spatial_filter', 'parent_map_digest', repmat('0', 1, 64), ...
    'parent_time_reference', activation.time_reference, ...
    'parameters', struct('kind', 'spatial_filter'));
spatial_bad = activation;
spatial_bad.method.parameters_json = tab.jcs_json(spatial_payload);
spatial_bad.method.parameters_sha256 = tab.restore_domain_digest( ...
    'OM-ACTIVATION-METHOD', 'method-v1', spatial_payload);
[spatial_ok, spatial_err, ~] = tab.validate_activation_compatibility( ...
    spatial_bad, activation);
record('E2C4', ~spatial_ok && contains(spatial_err, 'method'), spatial_err);

fprintf('E2C5: manual_zero method parameters are semantically closed\n');
zero_payload = struct('schema', 'method-parameters-v1', ...
    'operation', 'manual_zero', 'parent_map_digest', repmat('0', 1, 64), ...
    'parent_time_reference', activation.time_reference, ...
    'parameters', struct('kind', 'manual_zero'));
zero_bad = activation;
zero_bad.method.parameters_json = tab.jcs_json(zero_payload);
zero_bad.method.parameters_sha256 = tab.restore_domain_digest( ...
    'OM-ACTIVATION-METHOD', 'method-v1', zero_payload);
[zero_ok, zero_err, ~] = tab.validate_activation_compatibility( ...
    zero_bad, activation);
record('E2C5', ~zero_ok && contains(zero_err, 'method'), zero_err);

fprintf('E2C6: undo method parameters are semantically closed\n');
undo_payload = struct('schema', 'method-parameters-v1', ...
    'operation', 'undo', 'parent_map_digest', repmat('0', 1, 64), ...
    'parent_time_reference', activation.time_reference, ...
    'parameters', struct('kind', 'undo'));
undo_bad = activation;
undo_bad.method.parameters_json = tab.jcs_json(undo_payload);
undo_bad.method.parameters_sha256 = tab.restore_domain_digest( ...
    'OM-ACTIVATION-METHOD', 'method-v1', undo_payload);
[undo_ok, undo_err, ~] = tab.validate_activation_compatibility( ...
    undo_bad, activation);
record('E2C6', ~undo_ok && contains(undo_err, 'method'), undo_err);

fprintf('E5C1: recovery operation has a public executable seam\n');
record('E5C1', ismethod(tab, 'recover_sidecar'), 'recover_sidecar is missing');

fprintf('E4C1: assigned zero and canonical NaN remain distinct in the wire\n');
[po_ok, po_err, projected] = tab.validate_projected_output([0; NaN], ...
    repmat('1', 1, 64), repmat('2', 1, 64));
[assigned, counts] = tab.classify_projected_output(projected);
record('E4C1', po_ok && isempty(po_err) && assigned(1) && ~assigned(2) && ...
    counts.assigned == 1 && counts.unassigned == 1, po_err);

fprintf('PROBE_RESTORE_CAMERA_ACTIVATION_SIDECAR RESULT: %d passed, %d failed\n', pass, fail);
if fail ~= 0
    error('PROBE_FAIL probe_restore_camera_activation_sidecar');
end
fprintf('PROBE_OK probe_restore_camera_activation_sidecar %d/0\n', pass);

    function record(name, condition, detail)
        if condition
            pass = pass + 1;
            result = 'PASS';
        else
            fail = fail + 1;
            result = 'FAIL';
        end
        fprintf('  %s %s %s\n', name, result, detail);
    end
end

function json = method_parameters_json(tab)
payload = struct('schema', 'method-parameters-v1', 'operation', 'load', ...
    'parent_map_digest', [], 'parent_time_reference', [], ...
    'parameters', struct('kind', 'load', ...
    'source_recording_identity_sha256', repmat('0', 1, 64), ...
    'initial_time_reference', struct('kind', 'relative_to_first_frame', ...
    'anchor_frame', '1', 'applied_offset_ms', '0000000000000000', ...
    'parent', [])));
json = tab.jcs_json(payload);
end

function camera = camera_record(view_angle)
camera = struct('position', [1 2 3], 'target', [0 0 0], 'up', [0 0 1], ...
    'view_angle', view_angle, 'limits', struct( ...
    'fused', struct('x', [-1 1], 'y', [-2 2], 'z', [-3 3]), ...
    'rebuilt', struct('x', [-4 4], 'y', [-5 5], 'z', [-6 6]), ...
    'projected', struct('x', [-7 7], 'y', [-8 8], 'z', [-9 9])));
end
